-- Esquema de huella hídrica y de carbono para PostgreSQL.
-- MySQL usa AUTO_INCREMENT, UNSIGNED y ENGINE=InnoDB. Postgres no.
-- id_rol queda INTEGER en la tabla y en la llave foránea (antes no coincidían).
-- fecha_actualizacion se actualiza con un trigger: Postgres no tiene ON UPDATE CURRENT_TIMESTAMP.

CREATE OR REPLACE FUNCTION set_fecha_actualizacion()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.fecha_actualizacion := CURRENT_TIMESTAMP;
  RETURN NEW;
END;
$$;

CREATE TABLE rol (
  id_rol INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(50) NOT NULL UNIQUE,
  descripcion VARCHAR(255),
  estado BOOLEAN NOT NULL DEFAULT TRUE,
  fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE usuario (
  id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombres VARCHAR(100) NOT NULL,
  apellidos VARCHAR(100) NOT NULL,
  correo VARCHAR(150) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  estado BOOLEAN NOT NULL DEFAULT TRUE,
  fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  fecha_actualizacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  fecha_ultimo_acceso TIMESTAMPTZ NULL,
  CONSTRAINT chk_usuario_correo CHECK (correo LIKE '%@%')
);

CREATE TRIGGER trg_usuario_fecha_actualizacion
BEFORE UPDATE ON usuario
FOR EACH ROW
EXECUTE PROCEDURE set_fecha_actualizacion();

CREATE TABLE usuario_rol (
  id_usuario BIGINT NOT NULL,
  id_rol INTEGER NOT NULL,
  fecha_asignacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id_usuario, id_rol),
  FOREIGN KEY (id_usuario) REFERENCES usuario (id_usuario) ON UPDATE CASCADE ON DELETE CASCADE,
  FOREIGN KEY (id_rol) REFERENCES rol (id_rol) ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE permiso (
  id_permiso INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo VARCHAR(80) NOT NULL UNIQUE,
  nombre VARCHAR(120) NOT NULL,
  fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE rol_permiso (
  id_rol INTEGER NOT NULL,
  id_permiso INTEGER NOT NULL,
  fecha_asignacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id_rol, id_permiso),
  FOREIGN KEY (id_rol) REFERENCES rol (id_rol) ON UPDATE CASCADE ON DELETE RESTRICT,
  FOREIGN KEY (id_permiso) REFERENCES permiso (id_permiso) ON UPDATE CASCADE ON DELETE CASCADE
);

CREATE TABLE departamento (
  id_departamento INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo VARCHAR(2) NOT NULL UNIQUE,
  nombre VARCHAR(120) NOT NULL UNIQUE,
  estado BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE municipio (
  id_municipio INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_departamento INTEGER NOT NULL,
  codigo VARCHAR(5) NOT NULL UNIQUE,
  nombre VARCHAR(150) NOT NULL,
  estado BOOLEAN NOT NULL DEFAULT TRUE,
  UNIQUE (id_departamento, nombre),
  FOREIGN KEY (id_departamento) REFERENCES departamento (id_departamento) ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE organizacion (
  id_organizacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_municipio INTEGER NOT NULL,
  nombre VARCHAR(200) NOT NULL,
  nombre_corto VARCHAR(50),
  nit VARCHAR(20) NOT NULL,
  tipo VARCHAR(30) NOT NULL,
  sector_economico VARCHAR(120),
  correo VARCHAR(150),
  telefono VARCHAR(30),
  direccion VARCHAR(200),
  representante_nombre VARCHAR(150),
  representante_tipo_documento VARCHAR(20),
  representante_numero_documento VARCHAR(30),
  representante_correo VARCHAR(150),
  representante_telefono VARCHAR(30),
  estado BOOLEAN NOT NULL DEFAULT TRUE,
  fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (id_municipio, nombre),
  CHECK (tipo IN ('EMPRESA', 'ENTIDAD_PUBLICA', 'INSTITUCION_EDUCATIVA', 'ONG', 'OTRA')),
  CHECK (
    representante_tipo_documento IS NULL
    OR representante_tipo_documento IN ('CC', 'CE', 'PASAPORTE')
  ),
  FOREIGN KEY (id_municipio) REFERENCES municipio (id_municipio) ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE UNIQUE INDEX uq_organizacion_nombre_corto
  ON organizacion (id_municipio, nombre_corto)
  WHERE nombre_corto IS NOT NULL;

CREATE TABLE sede (
  id_sede BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_organizacion BIGINT NOT NULL,
  codigo VARCHAR(30),
  nombre VARCHAR(150) NOT NULL,
  direccion VARCHAR(200),
  telefono VARCHAR(30),
  correo VARCHAR(150),
  responsable_nombre VARCHAR(150),
  responsable_cargo VARCHAR(100),
  responsable_correo VARCHAR(150),
  responsable_telefono VARCHAR(30),
  estado BOOLEAN NOT NULL DEFAULT TRUE,
  fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (id_organizacion, nombre),
  FOREIGN KEY (id_organizacion) REFERENCES organizacion (id_organizacion) ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE UNIQUE INDEX uq_sede_codigo
  ON sede (id_organizacion, codigo)
  WHERE codigo IS NOT NULL;

CREATE TABLE usuario_sede (
  id_usuario BIGINT NOT NULL,
  id_sede BIGINT NOT NULL,
  fecha_asignacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id_usuario, id_sede),
  FOREIGN KEY (id_usuario) REFERENCES usuario (id_usuario) ON UPDATE CASCADE ON DELETE CASCADE,
  FOREIGN KEY (id_sede) REFERENCES sede (id_sede) ON UPDATE CASCADE ON DELETE CASCADE
);

CREATE TABLE proceso (
  id_proceso BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_sede BIGINT NOT NULL,
  nombre VARCHAR(150) NOT NULL,
  descripcion TEXT,
  estado BOOLEAN NOT NULL DEFAULT TRUE,
  fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (id_sede, nombre),
  FOREIGN KEY (id_sede) REFERENCES sede (id_sede) ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE actividad (
  id_actividad BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_proceso BIGINT NOT NULL,
  nombre VARCHAR(150) NOT NULL,
  descripcion TEXT,
  estado BOOLEAN NOT NULL DEFAULT TRUE,
  fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (id_proceso, nombre),
  FOREIGN KEY (id_proceso) REFERENCES proceso (id_proceso) ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE periodo_medicion (
  id_periodo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_organizacion BIGINT NOT NULL,
  nombre VARCHAR(100) NOT NULL,
  fecha_inicio DATE NOT NULL,
  fecha_fin DATE NOT NULL,
  estado VARCHAR(20) NOT NULL DEFAULT 'ABIERTO',
  fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (id_organizacion, nombre),
  CHECK (fecha_fin >= fecha_inicio),
  CHECK (estado IN ('ABIERTO', 'CERRADO', 'BLOQUEADO')),
  FOREIGN KEY (id_organizacion) REFERENCES organizacion (id_organizacion) ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE unidad_medida (
  id_unidad INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo VARCHAR(30) NOT NULL UNIQUE,
  nombre VARCHAR(100) NOT NULL,
  simbolo VARCHAR(30) NOT NULL,
  magnitud VARCHAR(50) NOT NULL,
  factor_base DECIMAL(24, 12) NOT NULL DEFAULT 1,
  estado BOOLEAN NOT NULL DEFAULT TRUE,
  CHECK (factor_base > 0)
);

CREATE TABLE metodologia (
  id_metodologia BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo VARCHAR(50) NOT NULL UNIQUE,
  nombre VARCHAR(150) NOT NULL,
  tipo VARCHAR(20) NOT NULL,
  descripcion TEXT,
  entidad_fuente VARCHAR(150),
  estado BOOLEAN NOT NULL DEFAULT TRUE,
  fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CHECK (tipo IN ('HIDRICA', 'CARBONO'))
);

CREATE TABLE metodologia_version (
  id_version BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_metodologia BIGINT NOT NULL,
  numero_version VARCHAR(30) NOT NULL,
  fecha_inicio_vigencia DATE NOT NULL,
  fecha_fin_vigencia DATE,
  descripcion TEXT,
  estado BOOLEAN NOT NULL DEFAULT TRUE,
  fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (id_metodologia, numero_version),
  CHECK (fecha_fin_vigencia IS NULL OR fecha_fin_vigencia >= fecha_inicio_vigencia),
  FOREIGN KEY (id_metodologia) REFERENCES metodologia (id_metodologia) ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE tipo_agua (
  id_tipo_agua INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo VARCHAR(30) NOT NULL UNIQUE,
  nombre VARCHAR(100) NOT NULL UNIQUE,
  descripcion TEXT,
  estado BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE componente_hidrico (
  id_componente_hidrico INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo VARCHAR(30) NOT NULL UNIQUE,
  nombre VARCHAR(100) NOT NULL UNIQUE,
  descripcion TEXT,
  estado BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE dato_hidrico (
  id_dato_hidrico BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_actividad BIGINT NOT NULL,
  id_periodo BIGINT NOT NULL,
  id_tipo_agua INTEGER NOT NULL,
  id_unidad INTEGER NOT NULL,
  id_usuario_registro BIGINT NOT NULL,
  cantidad DECIMAL(20, 6) NOT NULL,
  fecha_dato DATE,
  fuente_dato VARCHAR(255),
  observacion TEXT,
  estado_registro VARCHAR(20) NOT NULL DEFAULT 'REGISTRADO',
  fecha_registro TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  fecha_actualizacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CHECK (cantidad >= 0),
  CHECK (estado_registro IN ('REGISTRADO', 'VALIDADO', 'RECHAZADO')),
  FOREIGN KEY (id_actividad) REFERENCES actividad (id_actividad) ON DELETE RESTRICT,
  FOREIGN KEY (id_periodo) REFERENCES periodo_medicion (id_periodo) ON DELETE RESTRICT,
  FOREIGN KEY (id_tipo_agua) REFERENCES tipo_agua (id_tipo_agua) ON DELETE RESTRICT,
  FOREIGN KEY (id_unidad) REFERENCES unidad_medida (id_unidad) ON DELETE RESTRICT,
  FOREIGN KEY (id_usuario_registro) REFERENCES usuario (id_usuario) ON DELETE RESTRICT
);

CREATE TRIGGER trg_dato_hidrico_fecha_actualizacion
BEFORE UPDATE ON dato_hidrico
FOR EACH ROW
EXECUTE PROCEDURE set_fecha_actualizacion();

CREATE TABLE parametro_hidrico (
  id_parametro_hidrico BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_version BIGINT NOT NULL,
  id_unidad INTEGER,
  codigo VARCHAR(50) NOT NULL,
  nombre VARCHAR(150) NOT NULL,
  valor DECIMAL(24, 10) NOT NULL,
  fuente VARCHAR(255),
  fecha_inicio_vigencia DATE NOT NULL,
  fecha_fin_vigencia DATE,
  estado BOOLEAN NOT NULL DEFAULT TRUE,
  UNIQUE (id_version, codigo, fecha_inicio_vigencia),
  CHECK (fecha_fin_vigencia IS NULL OR fecha_fin_vigencia >= fecha_inicio_vigencia),
  FOREIGN KEY (id_version) REFERENCES metodologia_version (id_version) ON DELETE RESTRICT,
  FOREIGN KEY (id_unidad) REFERENCES unidad_medida (id_unidad) ON DELETE RESTRICT
);

CREATE TABLE calculo_hidrico (
  id_calculo_hidrico BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_organizacion BIGINT NOT NULL,
  id_periodo BIGINT NOT NULL,
  id_version BIGINT NOT NULL,
  id_usuario BIGINT NOT NULL,
  fecha_calculo TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  estado VARCHAR(20) NOT NULL DEFAULT 'BORRADOR',
  total_huella DECIMAL(24, 8),
  id_unidad_resultado INTEGER,
  observacion TEXT,
  CHECK (estado IN ('BORRADOR', 'VALIDADO', 'CALCULADO', 'APROBADO', 'HISTORICO')),
  CHECK (total_huella IS NULL OR total_huella >= 0),
  FOREIGN KEY (id_organizacion) REFERENCES organizacion (id_organizacion) ON DELETE RESTRICT,
  FOREIGN KEY (id_periodo) REFERENCES periodo_medicion (id_periodo) ON DELETE RESTRICT,
  FOREIGN KEY (id_version) REFERENCES metodologia_version (id_version) ON DELETE RESTRICT,
  FOREIGN KEY (id_usuario) REFERENCES usuario (id_usuario) ON DELETE RESTRICT,
  FOREIGN KEY (id_unidad_resultado) REFERENCES unidad_medida (id_unidad) ON DELETE RESTRICT
);

CREATE TABLE calculo_hidrico_dato (
  id_calculo_hidrico BIGINT NOT NULL,
  id_dato_hidrico BIGINT NOT NULL,
  PRIMARY KEY (id_calculo_hidrico, id_dato_hidrico),
  FOREIGN KEY (id_calculo_hidrico) REFERENCES calculo_hidrico (id_calculo_hidrico) ON DELETE CASCADE,
  FOREIGN KEY (id_dato_hidrico) REFERENCES dato_hidrico (id_dato_hidrico) ON DELETE RESTRICT
);

CREATE TABLE calculo_hidrico_parametro (
  id_calculo_hidrico BIGINT NOT NULL,
  id_parametro_hidrico BIGINT NOT NULL,
  valor_aplicado DECIMAL(24, 10) NOT NULL,
  PRIMARY KEY (id_calculo_hidrico, id_parametro_hidrico),
  FOREIGN KEY (id_calculo_hidrico) REFERENCES calculo_hidrico (id_calculo_hidrico) ON DELETE CASCADE,
  FOREIGN KEY (id_parametro_hidrico) REFERENCES parametro_hidrico (id_parametro_hidrico) ON DELETE RESTRICT
);

CREATE TABLE resultado_hidrico (
  id_resultado_hidrico BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_calculo_hidrico BIGINT NOT NULL,
  id_actividad BIGINT,
  id_componente_hidrico INTEGER NOT NULL,
  id_unidad INTEGER NOT NULL,
  valor DECIMAL(24, 8) NOT NULL,
  fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CHECK (valor >= 0),
  FOREIGN KEY (id_calculo_hidrico) REFERENCES calculo_hidrico (id_calculo_hidrico) ON DELETE CASCADE,
  FOREIGN KEY (id_actividad) REFERENCES actividad (id_actividad) ON DELETE RESTRICT,
  FOREIGN KEY (id_componente_hidrico) REFERENCES componente_hidrico (id_componente_hidrico) ON DELETE RESTRICT,
  FOREIGN KEY (id_unidad) REFERENCES unidad_medida (id_unidad) ON DELETE RESTRICT
);

CREATE TABLE alcance_emision (
  id_alcance INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo VARCHAR(20) NOT NULL UNIQUE,
  nombre VARCHAR(100) NOT NULL UNIQUE,
  descripcion TEXT,
  estado BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE fuente_emision (
  id_fuente_emision BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo VARCHAR(50) NOT NULL UNIQUE,
  nombre VARCHAR(150) NOT NULL,
  categoria VARCHAR(100),
  descripcion TEXT,
  estado BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE dato_actividad_carbono (
  id_dato_carbono BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_actividad BIGINT NOT NULL,
  id_periodo BIGINT NOT NULL,
  id_fuente_emision BIGINT NOT NULL,
  id_alcance INTEGER NOT NULL,
  id_unidad INTEGER NOT NULL,
  id_usuario_registro BIGINT NOT NULL,
  cantidad DECIMAL(24, 8) NOT NULL,
  fecha_dato DATE,
  fuente_dato VARCHAR(255),
  observacion TEXT,
  estado_registro VARCHAR(20) NOT NULL DEFAULT 'REGISTRADO',
  fecha_registro TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  fecha_actualizacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CHECK (cantidad >= 0),
  CHECK (estado_registro IN ('REGISTRADO', 'VALIDADO', 'RECHAZADO')),
  FOREIGN KEY (id_actividad) REFERENCES actividad (id_actividad) ON DELETE RESTRICT,
  FOREIGN KEY (id_periodo) REFERENCES periodo_medicion (id_periodo) ON DELETE RESTRICT,
  FOREIGN KEY (id_fuente_emision) REFERENCES fuente_emision (id_fuente_emision) ON DELETE RESTRICT,
  FOREIGN KEY (id_alcance) REFERENCES alcance_emision (id_alcance) ON DELETE RESTRICT,
  FOREIGN KEY (id_unidad) REFERENCES unidad_medida (id_unidad) ON DELETE RESTRICT,
  FOREIGN KEY (id_usuario_registro) REFERENCES usuario (id_usuario) ON DELETE RESTRICT
);

CREATE TRIGGER trg_dato_carbono_fecha_actualizacion
BEFORE UPDATE ON dato_actividad_carbono
FOR EACH ROW
EXECUTE PROCEDURE set_fecha_actualizacion();

CREATE TABLE factor_emision (
  id_factor_emision BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_version BIGINT NOT NULL,
  id_fuente_emision BIGINT NOT NULL,
  id_unidad_entrada INTEGER NOT NULL,
  id_unidad_salida INTEGER NOT NULL,
  codigo VARCHAR(80) NOT NULL,
  nombre VARCHAR(150) NOT NULL,
  valor DECIMAL(24, 12) NOT NULL,
  fuente VARCHAR(255),
  region VARCHAR(100),
  fecha_inicio_vigencia DATE NOT NULL,
  fecha_fin_vigencia DATE,
  estado BOOLEAN NOT NULL DEFAULT TRUE,
  fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (id_version, codigo, fecha_inicio_vigencia),
  CHECK (valor >= 0),
  CHECK (fecha_fin_vigencia IS NULL OR fecha_fin_vigencia >= fecha_inicio_vigencia),
  FOREIGN KEY (id_version) REFERENCES metodologia_version (id_version) ON DELETE RESTRICT,
  FOREIGN KEY (id_fuente_emision) REFERENCES fuente_emision (id_fuente_emision) ON DELETE RESTRICT,
  FOREIGN KEY (id_unidad_entrada) REFERENCES unidad_medida (id_unidad) ON DELETE RESTRICT,
  FOREIGN KEY (id_unidad_salida) REFERENCES unidad_medida (id_unidad) ON DELETE RESTRICT
);

CREATE TABLE calculo_carbono (
  id_calculo_carbono BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_organizacion BIGINT NOT NULL,
  id_periodo BIGINT NOT NULL,
  id_version BIGINT NOT NULL,
  id_usuario BIGINT NOT NULL,
  id_unidad_resultado INTEGER,
  fecha_calculo TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  estado VARCHAR(20) NOT NULL DEFAULT 'BORRADOR',
  total_co2e DECIMAL(24, 8),
  observacion TEXT,
  CHECK (estado IN ('BORRADOR', 'VALIDADO', 'CALCULADO', 'APROBADO', 'HISTORICO')),
  CHECK (total_co2e IS NULL OR total_co2e >= 0),
  FOREIGN KEY (id_organizacion) REFERENCES organizacion (id_organizacion) ON DELETE RESTRICT,
  FOREIGN KEY (id_periodo) REFERENCES periodo_medicion (id_periodo) ON DELETE RESTRICT,
  FOREIGN KEY (id_version) REFERENCES metodologia_version (id_version) ON DELETE RESTRICT,
  FOREIGN KEY (id_usuario) REFERENCES usuario (id_usuario) ON DELETE RESTRICT,
  FOREIGN KEY (id_unidad_resultado) REFERENCES unidad_medida (id_unidad) ON DELETE RESTRICT
);

CREATE TABLE calculo_carbono_dato (
  id_calculo_carbono BIGINT NOT NULL,
  id_dato_carbono BIGINT NOT NULL,
  PRIMARY KEY (id_calculo_carbono, id_dato_carbono),
  FOREIGN KEY (id_calculo_carbono) REFERENCES calculo_carbono (id_calculo_carbono) ON DELETE CASCADE,
  FOREIGN KEY (id_dato_carbono) REFERENCES dato_actividad_carbono (id_dato_carbono) ON DELETE RESTRICT
);

CREATE TABLE calculo_carbono_factor (
  id_calculo_carbono BIGINT NOT NULL,
  id_factor_emision BIGINT NOT NULL,
  valor_aplicado DECIMAL(24, 12) NOT NULL,
  PRIMARY KEY (id_calculo_carbono, id_factor_emision),
  FOREIGN KEY (id_calculo_carbono) REFERENCES calculo_carbono (id_calculo_carbono) ON DELETE CASCADE,
  FOREIGN KEY (id_factor_emision) REFERENCES factor_emision (id_factor_emision) ON DELETE RESTRICT
);

CREATE TABLE resultado_carbono (
  id_resultado_carbono BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_calculo_carbono BIGINT NOT NULL,
  id_actividad BIGINT,
  id_alcance INTEGER NOT NULL,
  id_fuente_emision BIGINT NOT NULL,
  id_unidad INTEGER NOT NULL,
  valor_co2e DECIMAL(24, 8) NOT NULL,
  fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CHECK (valor_co2e >= 0),
  FOREIGN KEY (id_calculo_carbono) REFERENCES calculo_carbono (id_calculo_carbono) ON DELETE CASCADE,
  FOREIGN KEY (id_actividad) REFERENCES actividad (id_actividad) ON DELETE RESTRICT,
  FOREIGN KEY (id_alcance) REFERENCES alcance_emision (id_alcance) ON DELETE RESTRICT,
  FOREIGN KEY (id_fuente_emision) REFERENCES fuente_emision (id_fuente_emision) ON DELETE RESTRICT,
  FOREIGN KEY (id_unidad) REFERENCES unidad_medida (id_unidad) ON DELETE RESTRICT
);

CREATE TABLE auditoria (
  id_auditoria BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario BIGINT,
  modulo VARCHAR(50) NOT NULL,
  entidad VARCHAR(100) NOT NULL,
  id_entidad BIGINT,
  accion VARCHAR(50) NOT NULL,
  valor_anterior JSONB,
  valor_nuevo JSONB,
  direccion_ip VARCHAR(45),
  user_agent VARCHAR(500),
  fecha TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CHECK (accion IN ('INSERTAR', 'ACTUALIZAR', 'ELIMINAR', 'VALIDAR', 'CALCULAR', 'APROBAR', 'CONSULTAR', 'IMPORTAR', 'INICIAR_SESION')),
  FOREIGN KEY (id_usuario) REFERENCES usuario (id_usuario) ON DELETE SET NULL
);

